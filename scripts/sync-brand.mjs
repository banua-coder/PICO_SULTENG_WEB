#!/usr/bin/env node
/**
 * Copy the brand assets from the PICO repo into this one, with a SHA-256 manifest (ADR-0105, spec 12).
 *
 *   pnpm sync:brand            copy from $PICO_BRAND_DIR (default ../../PICO/brand) and rewrite brand.manifest.json
 *   pnpm check:brand           fail if a committed copy differs from the manifest (CI), or if the source moved on
 *
 * The PICO repo stays the source of truth. Never edit files under src/assets/brand/ by hand.
 */
import { createHash } from 'node:crypto'
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
export const ROOT = resolve(HERE, '..')
const MANIFEST = 'brand.manifest.json'
const OWNED = 'src/assets/brand' // fully owned by the sync: unlisted files here count as drift

const ext = (...e) => (name) => e.some((x) => name.endsWith(x))
const list = (dir, keep) => (existsSync(dir) ? readdirSync(dir).filter((n) => statSync(join(dir, n)).isFile() && keep(n)) : [])

/** The fixed file list: [source relative to brand/, destination relative to the web root]. */
export function plan(brand) {
  const out = [['tokens/pico-tokens.css', `${OWNED}/pico-tokens.css`]]
  const add = (srcDir, destDir, keep) => list(join(brand, srcDir), keep).forEach((n) => out.push([`${srcDir}/${n}`, `${destDir}/${n}`]))
  add('icons/mono', `${OWNED}/icons/mono`, ext('.svg'))
  add('icons/duotone', `${OWNED}/icons/duotone`, ext('.svg'))
  add('icons', `${OWNED}/icons`, ext('index.json'))
  add('illustrations', `${OWNED}/illustrations`, ext('.svg'))
  add('patterns', `${OWNED}/patterns`, ext('.svg', '.json'))
  add('lottie', `${OWNED}/lottie`, ext('.json'))
  add('lottie/static', `${OWNED}/lottie/static`, ext('.svg'))
  add('logo', `${OWNED}/logo`, ext('.svg'))
  const pub = [
    ['logo/favicon/favicon.svg', 'public/favicon.svg'],
    ['logo/favicon/favicon.ico', 'public/favicon.ico'],
    ['logo/favicon/apple-touch-icon-180.png', 'public/apple-touch-icon-180.png'],
    ['logo/favicon/icon-192.png', 'public/icon-192.png'],
    ['logo/favicon/icon-512.png', 'public/icon-512.png'],
    ['logo/app-icon/app-icon-maskable-512.png', 'public/app-icon-maskable-512.png'],
    ['logo/og/og-image-1200x630.png', 'public/og-image-1200x630.png'],
  ]
  return [...out, ...pub]
}

const sha = (file) => createHash('sha256').update(readFileSync(file)).digest('hex')

function walk(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(join(dir, d.name)) : [join(dir, d.name)]))
}

export function syncBrand({ source, root = ROOT }) {
  const files = plan(source)
  const missing = files.filter(([from]) => !existsSync(join(source, from)))
  if (missing.length) throw new Error(`brand source is missing: ${missing.map((m) => m[0]).join(', ')}`)
  rmSync(join(root, OWNED), { recursive: true, force: true })
  const manifest = {}
  for (const [from, to] of files) {
    mkdirSync(dirname(join(root, to)), { recursive: true })
    copyFileSync(join(source, from), join(root, to))
    manifest[to] = { from, sha256: sha(join(source, from)) }
  }
  // IconKey is generated from the icon index, so a new brand icon is a type error until it is used on purpose
  const index = JSON.parse(readFileSync(join(root, OWNED, 'icons/index.json'), 'utf8'))
  const keys = (index.icons ?? []).map((i) => i.key)
  const keysFile = `${OWNED}/icon-keys.ts`
  writeFileSync(
    join(root, keysFile),
    `// Generated by scripts/sync-brand.mjs from icons/index.json. Do not edit.\nexport const ICON_KEYS = ${JSON.stringify(keys)} as const\nexport type IconKey = (typeof ICON_KEYS)[number]\n`,
  )
  manifest[keysFile] = { from: 'icons/index.json (generated)', sha256: sha(join(root, keysFile)) }
  writeFileSync(join(root, MANIFEST), JSON.stringify(manifest, null, 2) + '\n')
  return Object.keys(manifest).length
}

/** Returns a list of problems. Empty means the committed copies match the manifest (and the source, if given). */
export function checkBrand({ root = ROOT, source } = {}) {
  const problems = []
  const mpath = join(root, MANIFEST)
  if (!existsSync(mpath)) return [`${MANIFEST} is missing. Run pnpm sync:brand`]
  const manifest = JSON.parse(readFileSync(mpath, 'utf8'))
  for (const [to, { from, sha256 }] of Object.entries(manifest)) {
    const f = join(root, to)
    if (!existsSync(f)) problems.push(`missing: ${to}`)
    else if (sha(f) !== sha256) problems.push(`changed by hand: ${to}`)
    if (source && existsSync(join(source, from)) && sha(join(source, from)) !== sha256) problems.push(`source moved on: ${from}`)
  }
  for (const f of walk(join(root, OWNED))) {
    const rel = relative(root, f).split('\\').join('/')
    if (!(rel in manifest)) problems.push(`not in manifest: ${rel}`)
  }
  return problems
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = resolve(process.env.PICO_BRAND_DIR || join(ROOT, '..', '..', 'PICO', 'brand'))
  if (process.argv.includes('--check')) {
    const problems = checkBrand({ source: existsSync(source) ? source : undefined })
    if (problems.length) {
      console.error(problems.join('\n') + '\nbrand copy has drifted. Run pnpm sync:brand and commit.')
      process.exit(1)
    }
    console.log(`brand ok${existsSync(source) ? ' (also matches the source)' : ' (source not found, manifest check only)'}`)
  } else {
    console.log(`synced ${syncBrand({ source })} files from ${source}`)
  }
}
